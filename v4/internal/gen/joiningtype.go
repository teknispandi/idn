// Generator joiningtype_table.go: menurunkan Joining_Type R, D dan L untuk
// properti LGR "jt:" (RFC 7940 §6.2.3) dari data Unicode milik
// golang.org/x/text, tanpa menyalin tabel Unicode dengan tangan.
//
// Caranya lewat aturan konteks ZWNJ (RFC 5892 A.1 / RFC 8264) yang
// diterapkan x/text/secure/precis: ZWNJ hanya sah di antara
// (L|D) T* ZWNJ T* (R|D). Dengan pembawa bertipe D:
//
//	pembawa + ZWNJ + X sah  ⇔  X bertipe R atau D
//	X + ZWNJ + pembawa sah  ⇔  X bertipe L atau D (virama dikecualikan,
//	                           karena virama juga meloloskan ZWNJ)
//
// x/net/idna tidak bisa dipakai: mesin statusnya memperlakukan tipe U
// setelah ZWNJ sama dengan R. Pembawa RTL (U+0628 BEH) dan LTR (U+1820
// MONGOLIAN A) dicoba keduanya karena aturan bidi menolak campuran arah.
// Tipe C, T dan U tidak dihasilkan.
//
// Jalankan: go generate ./v4
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"unicode"

	"golang.org/x/text/secure/precis"
	"golang.org/x/text/unicode/norm"
)

const zwnj = "‌"

var carriers = []rune{0x0628, 0x1820}

func valid(s string) bool {
	_, err := precis.UsernameCasePreserved.String(s)
	return err == nil
}

func isVirama(x rune) bool {
	return norm.NFC.PropertiesString(string(x)).CCC() == 9
}

func main() {
	var r, d, l []rune
	for x := rune(0); x <= unicode.MaxRune; x++ {
		if x == 0x200C || x == 0x200D || (x >= 0xD800 && x <= 0xDFFF) {
			continue
		}
		joinsRight, joinsLeft := false, false
		for _, c := range carriers {
			joinsRight = joinsRight || valid(string(c)+zwnj+string(x))
			joinsLeft = joinsLeft || (!isVirama(x) && valid(string(x)+zwnj+string(c)))
		}
		switch {
		case joinsRight && joinsLeft:
			d = append(d, x)
		case joinsRight:
			r = append(r, x)
		case joinsLeft:
			l = append(l, x)
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen/joiningtype.go; DO NOT EDIT.\n\n")
	b.WriteString("package v4\n\nimport \"unicode\"\n\n")
	b.WriteString("// Joining_Type dari tabel Unicode golang.org/x/text (lihat internal/gen/joiningtype.go).\n")
	b.WriteString("var joiningTypes = map[string]*unicode.RangeTable{\n")
	for _, t := range []struct {
		name  string
		runes []rune
	}{{"D", d}, {"L", l}, {"R", r}} {
		fmt.Fprintf(&b, "\t%q: %s,\n", t.name, rangeTable(t.runes))
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("joiningtype_table.go", src, 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("D=%d L=%d R=%d\n", len(d), len(l), len(r))
}

func rangeTable(runes []rune) string {
	var r16, r32 bytes.Buffer
	for i := 0; i < len(runes); {
		j := i
		for j+1 < len(runes) && runes[j+1] == runes[j]+1 {
			j++
		}
		lo, hi := runes[i], runes[j]
		if hi <= 0xFFFF {
			fmt.Fprintf(&r16, "{0x%04X, 0x%04X, 1},\n", lo, hi)
		} else {
			fmt.Fprintf(&r32, "{0x%05X, 0x%05X, 1},\n", lo, hi)
		}
		i = j + 1
	}
	return fmt.Sprintf("{R16: []unicode.Range16{\n%s}, R32: []unicode.Range32{\n%s}}", r16.String(), r32.String())
}
